-- M4: physical stock counts (stocktakes). No warehouse lock: a count compares the
-- photo taken at start against the stock now, minus the movements posted after it.
-- Hand-written (not `prisma migrate dev`).

-- CreateEnum
CREATE TYPE "HotelStocktakeStatus" AS ENUM ('DRAFT', 'COUNTING', 'PENDING_APPROVAL', 'APPLIED', 'CANCELLED');

-- CreateTable
CREATE TABLE "hotel_stocktakes" (
    "id" TEXT NOT NULL,
    "folio" TEXT NOT NULL,
    "warehouseId" TEXT NOT NULL,
    "status" "HotelStocktakeStatus" NOT NULL DEFAULT 'DRAFT',
    "blind" BOOLEAN NOT NULL DEFAULT true,
    "notes" TEXT,
    "createdById" TEXT NOT NULL,
    "snapshotAt" TIMESTAMP(3),
    "openedAt" TIMESTAMP(3),
    "closedById" TEXT,
    "closedAt" TIMESTAMP(3),
    "approvedById" TEXT,
    "approvedAt" TIMESTAMP(3),
    "cancelledAt" TIMESTAMP(3),
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL,

    CONSTRAINT "hotel_stocktakes_pkey" PRIMARY KEY ("id")
);

CREATE TABLE "hotel_stocktake_lines" (
    "id" TEXT NOT NULL,
    "stocktakeId" TEXT NOT NULL,
    "productId" TEXT NOT NULL,
    "locationId" TEXT NOT NULL,
    "systemQty" DECIMAL(12,3),
    "countedQty" DECIMAL(12,3),
    "countedById" TEXT,
    "countedAt" TIMESTAMP(3),
    "notes" TEXT,

    CONSTRAINT "hotel_stocktake_lines_pkey" PRIMARY KEY ("id")
);

-- AlterTable: movements generated by a count point to it
ALTER TABLE "hotel_movements" ADD COLUMN "stocktakeId" TEXT;

-- CreateIndex
CREATE UNIQUE INDEX "hotel_stocktakes_folio_key" ON "hotel_stocktakes"("folio");
CREATE INDEX "hotel_stocktakes_warehouseId_status_idx" ON "hotel_stocktakes"("warehouseId", "status");
CREATE UNIQUE INDEX "hotel_stocktake_lines_stocktakeId_productId_locationId_key" ON "hotel_stocktake_lines"("stocktakeId", "productId", "locationId");

-- One open count per warehouse at a time (M4 4.1).
CREATE UNIQUE INDEX "hotel_stocktakes_open_per_warehouse" ON "hotel_stocktakes"("warehouseId")
    WHERE "status" IN ('DRAFT', 'COUNTING', 'PENDING_APPROVAL');

